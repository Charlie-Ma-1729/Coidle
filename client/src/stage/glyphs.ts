/** 把字元對應到顏色 */
export function glyphPalette(tone: number): Record<string, number> {
  const light = lighten(tone, 0.45);
  return { "#": tone, "+": light, "2": light, "-": darken(tone, 0.35), k: 0x241f33, w: 0xffffff };
}
