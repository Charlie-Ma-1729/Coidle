/** 把家族／業態 id 清單展開成業態 id 清單（排序、去重）。打錯字或跨群組直接丟錯，避免悄悄少一塊。 */
export function expandFam(tokens: string[], group: CategoryGroup): string[] {
  const out = new Set<string>();
  for (const t of tokens) {
    const members = FAMILIES[t] ?? (CATEGORY_BY_ID[t] ? [t] : null);
    if (!members) throw new Error(`素材指定了不存在的家族或業態：${t}`);
    for (const c of members) {
      if (CATEGORY_BY_ID[c]?.group !== group) throw new Error(`素材（${group}）指定了不同類型的業態：${t} → ${c}`);
      out.add(c);
    }
  }
  return [...out].sort();
}

